const (
	demoDays        = 7
	demoHorizonBars = 12
	demoFeeBps      = 10
	demoLabelDays   = 6 // days 1..6 are labeled; day 7 is still inside its window
)

// demoStart is the first UTC day of the synthetic week. The timestamps are
// fixed so two demo runs produce the same report on every machine.
var demoStart = time.Date(2026, 11, 1, 0, 0, 0, 0, time.UTC)

// demoNow is the clock the report sees: the end of the synthetic week.
var demoNow = demoStart.AddDate(0, 0, demoDays)

// demoSymbols is the same liquid USDT basket as init --quick.
var demoSymbols = []string{
	"BTCUSDT", "ETHUSDT", "SOLUSDT", "BNBUSDT", "XRPUSDT",
	"DOGEUSDT", "ADAUSDT", "LINKUSDT", "AVAXUSDT", "LTCUSDT",
}

// cmdDemo seeds a deterministic synthetic week into a throwaway journal and
// prints the full report over it. The journal is marked runId=demo, so the
// report and status treat it as synthetic and never as G1 evidence.
func (r *runner) cmdDemo(args []string) int {
	g, rest, gerr := splitGlobals(args)
	if gerr != nil {
		return r.fail(false, exitUsage, codeUsage, gerr.Error(),
			"run vend demo [--json] [--keep] [--data-dir DIR]", false, nil)
	}
	jsonOut := g.json
	fs := r.newFlagSet("demo")
	keep := fs.Bool("keep", false, "keep the synthetic data directory")
	share := fs.Bool("share", false, "not supported: a synthetic journal is not G1 evidence")
	if err := fs.Parse(rest); err != nil {
		return exitUsage
	}
	if fs.NArg() > 0 {
		return r.fail(jsonOut, exitUsage, codeUsage,
			fmt.Sprintf("unexpected argument %q", fs.Arg(0)),
			"run vend demo [--json] [--keep] [--data-dir DIR]", false, nil)
	}
	if *share {
		return r.fail(jsonOut, exitUsage, codeUsage,
			"synthetic journal is not G1 evidence",
			"run vend demo for a walkthrough, or report a real data directory", false, nil)
	}

	dir, explicit, err := demoDataDir(g.dataDir)
	if err != nil {
		return r.fail(jsonOut, exitGeneral, codeGeneral, err.Error(),
			"choose a writable directory and retry", false, nil)
	}
	if !explicit && !*keep {
		defer func() { _ = os.RemoveAll(dir) }()
	}
	dbPath := config.DBPath(dir)
	if _, statErr := os.Stat(dbPath); statErr == nil {
		return r.fail(jsonOut, exitConflict, codeConflict,
			fmt.Sprintf("refusing to seed a demo into an existing journal at %s", dbPath),
			"choose an empty --data-dir; a real journal must never be overwritten", false, nil)
	}

	ctx := context.Background()
	jr, closer, err := r.openJournalAt(dbPath)
	if err != nil {
		return r.fail(jsonOut, exitGeneral, codeGeneral, err.Error(),
			"check the data directory is writable and retry", false, nil)
	}
	defer func() { _ = closer.Close() }()

	if err := seedDemo(ctx, jr); err != nil {
		return r.fail(jsonOut, exitGeneral, codeGeneral, err.Error(),
			"check the data directory is writable and retry", false, nil)
	}
	b, err := report.New(jr, ports.Deps{Clock: func() time.Time { return demoNow }}, report.Config{
		HorizonBars: demoHorizonBars,
		Timeframe:   15 * time.Minute,
		MinLabeled:  100,
	})
	if err != nil {
		return r.fail(jsonOut, exitGeneral, codeGeneral, err.Error(),
			"check the vend wiring and retry", false, nil)
	}
	rep, err := b.Build(ctx)
	if err != nil {
		return r.fail(jsonOut, exitGeneral, codeGeneral, err.Error(),
			"check the demo journal and retry", false, nil)
	}
	win, err := journalWindow(ctx, jr)
	if err != nil {
		return r.fail(jsonOut, exitGeneral, codeGeneral, err.Error(),
			"check the demo journal and retry", false, nil)
	}
	rep.Days = win.days
	rep.ActiveDays = win.active

	if jsonOut {
		r.printJSON(rep)
	} else {
		fmt.Fprintln(r.stdout, "SYNTHETIC - not real market data")
		fmt.Fprintln(r.stdout, "This journal was generated by vend demo; it is not G1 evidence.")
		fmt.Fprintln(r.stdout)
		printReportHuman(r.stdout, rep, win.days, win)
		fmt.Fprintln(r.stdout)
		fmt.Fprintln(r.stdout, "SYNTHETIC - the numbers above come from a fixed synthetic week.")
	}
	if *keep {
		fmt.Fprintf(r.stdout, "\ndemo data dir: %s\nrun: vend status --data-dir %s\n", dir, dir)
	}
	return exitOK
}

// demoDataDir returns the directory to seed. Without --data-dir it creates a
// temporary directory; an explicit directory is created if missing and is
// never deleted by the command.
func demoDataDir(requested string) (dir string, explicit bool, err error) {
	if strings.TrimSpace(requested) != "" {
		dir, err = filepath.Abs(requested)
		if err != nil {
			return "", true, err
		}
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return "", true, err
		}
		return dir, true, nil
	}
	dir, err = os.MkdirTemp("", "vend-demo-*")
	if err != nil {
		return "", false, err
	}
	return dir, false, nil
}

// seedDemo writes seven UTC days of synthetic signals. Days 1..6 are labeled;
// day 7 is recent enough that its outcomes are not yet due at demoNow.
func seedDemo(ctx context.Context, jr ports.Journal) error {
	policy := demoPolicyHash()
	eventSeq := 0
	appendEvent := func(kind string, ts time.Time, decisionID string, payload any) error {
		raw, err := json.Marshal(payload)
		if err != nil {
			return err
		}
		eventSeq++
		_, err = jr.Append(ctx, domain.Event{
			EventID:       fmt.Sprintf("demo-ev-%05d", eventSeq),
			Kind:          kind,
			TS:            ts,
			SchemaVersion: domain.EventSchemaVersion,
			Payload:       raw,
			CodeVersion:   "demo",
			RunID:         "demo",
			DecisionID:    decisionID,
			PolicyHash:    policy,
		})
		return err
	}

	signal := 0
	for day := 0; day < demoDays; day++ {
		for _, symbol := range demoSymbols {
			for _, side := range []domain.Side{domain.SideBuy, domain.SideSell} {
				signal++
				ts := demoStart.AddDate(0, 0, day).Add(8 * time.Hour)
				if side == domain.SideSell {
					ts = demoStart.AddDate(0, 0, day).Add(20 * time.Hour)
				}
				sigID := fmt.Sprintf("demo-%02d-%03d", day+1, signal)
				decID := fmt.Sprintf("demo-dec-%03d", signal)
				pass := demoUnit("p:" + sigID)
				fact := demoUnit("f:"+sigID) < pass
				entryPrice := 100 + 50*demoUnit("ep:"+sigID)
				req := domain.GateRequest{
					SignalID: sigID,
					Instrument: domain.Instrument{
						Venue:  "binance",
						Symbol: symbol,
					},
					Side:       side,
					IntentKind: domain.IntentEntry,
					Timeframe:  "15m",
					TS:         ts,
					Price:      domain.MustParseDecimal(fmt.Sprintf("%.2f", entryPrice)),
					Source:     "strategy:demo",
					State:      map[string]float64{"rsi14": 40 + 20*demoUnit("rsi:"+sigID), "atrPct": 0.5},
				}
				if err := appendEvent(domain.EventGateRequest, ts, decID, req); err != nil {
					return err
				}
				resp := domain.DecisionResponse{
					Answers: map[string]domain.Answer{
						"risk_check": {
							Type:          domain.QuestionNoul,
							Probabilities: map[string]float64{"pass": pass},
						},
					},
					Model:          "demo-model",
					RequestedModel: "demo-model",
				}
				if err := appendEvent(domain.EventDecisionResponse, ts.Add(time.Minute), decID, resp); err != nil {
					return err
				}
				verdict := domain.VerdictAbstain
				code := "abstain"
				switch {
				case pass >= 0.55:
					verdict, code = domain.VerdictAllow, "allow"
				case pass < 0.50:
					verdict, code = domain.VerdictReject, "blocked"
				}
				ges := domain.GateVerdict{
					Verdict:    verdict,
					Code:       code,
					Reasons:    []string{"synthetic demo signal"},
					Checks:     []domain.Check{{Name: "risk_check", Passed: verdict == domain.VerdictAllow}},
					DecisionID: decID,
					Model:      "demo-model",
					PolicyHash: policy,
					DecidedAt:  ts.Add(2 * time.Minute),
				}
				if err := appendEvent(domain.EventGateVerdict, ts.Add(2*time.Minute), decID, ges); err != nil {
					return err
				}
				if day >= demoLabelDays {
					continue
				}
				entryTS := ts.Add(15 * time.Minute)
				exitTS := entryTS.Add(demoHorizonBars * 15 * time.Minute)
				gross := -0.008
				if fact {
					gross = 0.012
				}
				net := gross + (demoUnit("n:"+sigID)-0.5)*0.002 - 2*float64(demoFeeBps)/10000
				exitPrice := entryPrice * (1 + net)
				mfe := math.Abs(net) + 0.001
				outcome := domain.Outcome{
					SignalID:    sigID,
					DecisionID:  decID,
					Instrument:  req.Instrument,
					Side:        side,
					Timeframe:   "15m",
					EntryTS:     entryTS,
					EntryPrice:  req.Price,
					ExitTS:      exitTS,
					ExitPrice:   domain.MustParseDecimal(fmt.Sprintf("%.6f", exitPrice)),
					HorizonBars: demoHorizonBars,
					FeeBps:      demoFeeBps,
					GrossReturn: domain.MustParseDecimal(fmt.Sprintf("%.12f", gross)),
					NetReturn:   domain.MustParseDecimal(fmt.Sprintf("%.12f", net)),
					MFE:         domain.MustParseDecimal(fmt.Sprintf("%.12f", mfe)),
					MAE:         domain.MustParseDecimal(fmt.Sprintf("%.12f", -mfe)),
					CandlesHash: demoHashHex(sigID),
					LabeledAt:   exitTS.Add(time.Minute),
					ReceivedAt:  ts,
					PriceSource: "demo",
					EntryLagMS:  0,
				}
				if err := appendEvent(domain.EventOutcomeLabeled, exitTS.Add(time.Minute), decID, outcome); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

// demoUnit maps a label to a deterministic value in [0,1).
func demoUnit(label string) float64 {
	sum := sha256.Sum256([]byte(label))
	return float64(binary.BigEndian.Uint64(sum[:8])) / float64(^uint64(0))
}

// demoHashHex is a deterministic 64-hex digest used as CandlesHash.
func demoHashHex(label string) string {
	sum := sha256.Sum256([]byte(label))
	return hex.EncodeToString(sum[:])
}

// demoPolicyHash is the fixed policy hash of the synthetic journal.
func demoPolicyHash() string {
	return demoHashHex("demo-policy")
}
